<?php

namespace OpenSim\Provisioning;

use OpenSim\Config\GridFileService;
use OpenSim\Config\IniEditor;
use OpenSim\Config\TextFileService;
use OpenSim\Models\GridInfo;

/**
 * Writes the config of a simulator and of its regions.
 *
 * The simulator config is the only file the launcher gives to OpenSimulator.
 * It carries what makes the simulator its own (ports, database, folders,
 * estate) and includes the architecture of the grid, which brings the services
 * of the grid (see GridShared). What it does not set comes from the defaults of
 * the core. Nothing may be written in the core, so every folder OpenSimulator
 * would use by default (relative to the core) is given here.
 */
final class SimulatorConfig
{
    public function render(SimulatorPlan $plan): string
    {
        // A grid with a master (SimulatorMaster) has the rest: its simulators say only what makes them their own
        $master = SimulatorMaster::exists($plan->gridDir);
        $architecture = $plan->configDir() . '/config-include/' . ($plan->hypergrid ? 'GridHypergrid.ini' : 'Grid.ini');
        $slug = $plan->slug;

        $lines = [
            ";; Generated by opensim setup: simulator {$plan->simulatorName} of the grid {$plan->gridName}",
            '',
            '[Const]',
            ...$master
                ? []
                : [
                    'BinDirectory = "' . $plan->binDir() . '"',
                    'BaseHostname = "' . $plan->baseHostname . '"',
                    'BaseURL = "http://' . $plan->baseHostname . '"',
                    'PublicPort = ' . $plan->publicPort,
                    'PrivatePort = ' . $plan->privatePort,
                    'PrivURL = "${Const|BaseURL}"',
                    'EtcDirectory = "' . $plan->gridDir . '"',
                ],
            'DataDirectory = "' . $plan->dataDirectory . '"',
            'CacheDirectory = "' . $plan->cacheDirectory . '"',
            'LogsDirectory = "' . $plan->logsDirectory . '"',
            '',
            '[Startup]',
            'regionload_regionsdir = "' . $plan->regionsDir() . '"',
            ...$master
                ? []
                : [
                    'RegistryLocation = "${Const|DataDirectory}/registry"',
                ],
            'PIDFile = "${Const|CacheDirectory}/' . $slug . '.pid"',
            'ConsoleHistoryFile = "${Const|LogsDirectory}/' . $slug . '.OpenSimConsoleHistory.txt"',
            ...$master
                ? []
                : [
                    'crash_dir = "${Const|CacheDirectory}/crashes"',
                    'DecodedSculptMapPath = "${Const|CacheDirectory}/j2kDecodeCache"',
                ],
            '',
            '[Network]',
            'http_listener_port = ' . $plan->httpPort,
            ...$plan->consolePort > 0 && $plan->consoleMode === 'rest'
                ? [
                    ';; Remote (REST) console of the simulator: every right on it, from the',
                    ';; machine that has the port, in the block of ten ports of the simulator',
                    ...$plan->consoleHost !== '' ? ['ConsoleHost = "' . $plan->consoleHost . '"'] : [],
                    'ConsoleUser = "' . $plan->consoleUser . '"',
                    'ConsolePass = "' . $plan->consolePass . '"',
                    'console_port = ' . $plan->consolePort,
                ]
                : ($plan->consolePort > 0
                    ? [
                        ';; Remote (REST) console of the simulator: not enabled, its port is kept here,',
                        ';; in the block of ten ports of the simulator (ConsoleUser, ConsolePass, console_port)',
                        ';console_port = ' . $plan->consolePort,
                    ]
                    : []),
            ...self::lslHost($plan) !== '' ? ['ExternalHostNameForLSL = "' . self::lslHost($plan) . '"'] : [],
            '',
            '[DatabaseService]',
            ...$master ? [] : ['StorageProvider = "OpenSim.Data.MySQL.dll"'],
            'ConnectionString = "' . $plan->connectionString() . '"',
            '',
            ...$master
                ? []
                : [
                    '[GridService]',
                    'MapTileDirectory = "${Const|CacheDirectory}/maptiles"',
                    '',
                    ...self::gridLayer($plan, true),
                    '[YEngine]',
                    'ScriptEnginesPath = "${Const|DataDirectory}/ScriptEngines"',
                    '',
                    ';; OSSL is part of the standard config, as the grid sets it (its osslEnable.ini)',
                    '[OSSL]',
                    'Include-osslDefaultEnable = "' . $plan->configDir() . '/config-include/osslDefaultEnable.ini"',
                    '',
                ],
            '[Estates]',
            'DefaultEstateName = "' . $plan->estateName . '"',
            'DefaultEstateOwnerName = "' . $plan->estateOwner . '"',
            '',
            ...$master
                ? []
                : [
                    '[Architecture]',
                    'Include-Architecture = "' . $architecture . '"',
                    '',
                ],
        ];

        $text = implode("\n", $lines);
        if ($plan->presetSettings !== '' && !$master) {
            // The grid is joined by a preset and has no master: what the preset says for the simulators wins over what is above
            $ini = new IniEditor($text);
            $ini->overlay($plan->presetSettings);
            $text = $ini->toString();
        }

        return $text;
    }

    /**
     * What a grid decides for its simulators, as lines of config: the search, the offline messages, the profiles. In the config of
     * each simulator, or in the OpenSim.ini of the grid when it has a master (see SimulatorMaster).
     *
     * @param bool $paths with the folder of the snapshot, which the model gives a simulator that has a master
     * @return list<string>
     */
    public static function gridLayer(SimulatorPlan|GridInfo $from, bool $paths = false): array
    {
        $plan = $from instanceof SimulatorPlan;
        $name = self::dataServiceNameOf($plan ? $from->gridNick : $from->nick, $plan ? $from->gridName : $from->name);
        $search = $plan ? $from->searchUrl : $from->helperUrl('query');
        $register = $plan ? $from->registerUrl : $from->helperUrl('register');
        $offline = $plan ? $from->offlineUrl : $from->helperUrl('offline');

        return [
            ...$search !== ''
                ? [
                    ';; The search of the grid: the module of the simulator asks the helpers for the places, the land for sale...',
                    '[Search]',
                    'Module = OpenSimSearch',
                    'SearchURL = "' . $search . '"',
                    '',
                ]
                : [],
            '[DataSnapshot]',
            ...$paths ? ['snapshot_cache_directory = "${Const|CacheDirectory}/DataSnapshot"'] : [],
            ...$register !== ''
                ? [
                    ';; The search of the grid: the simulator tells its regions to the helpers',
                    'index_sims = true',
                    'gridname = "' . ($plan ? $from->gridName : $from->name) . '"',
                    'DATA_SRV_' . $name . ' = "' . $register . '"',
                ]
                : [],
            '',
            ...$offline !== ''
                ? [
                    ';; The offline messages are kept by the helpers of the grid',
                    '[Messaging]',
                    'OfflineMessageModule = OfflineMessageModule',
                    'OfflineMessageURL = "' . $offline . '"',
                    '',
                ]
                : [],
            ';; The profiles (and their classifieds) are kept by Robust, which the simulator asks',
            '[UserProfiles]',
            'ProfileServiceURL = "${Const|BaseURL}:${Const|PublicPort}"',
            '',
            ...in_array('BakedTextureService', $from->connectors, true)
                ? [
                    ';; The bakes of the avatars are kept by Robust',
                    '[XBakes]',
                    'URL = "${Const|PrivURL}:${Const|PrivatePort}"',
                    '',
                ]
                : [],
            ...in_array('GroupsServiceConnector', $from->connectors, true) ? self::groupsLayer($from) : [],
        ];
    }

    /**
     * The host the scripts of the simulator see as its own: the address of the machine it runs on, never the host of a grid
     * that is somewhere else. The address its regions announce when it is given; else the host of the grid when the simulator
     * runs on the machine of the grid; else the name of the machine, empty when it has no name of its own (OpenSimulator then
     * takes the one of its regions).
     */
    public static function lslHost(SimulatorPlan $plan): string
    {
        $host = trim($plan->externalHost);
        if ($host !== '' && strcasecmp($host, 'SYSTEMIP') !== 0) {
            return $host;
        }
        if ($plan->gridHere && $plan->preset === '') {
            return '${Const|BaseHostname}';
        }
        $name = (string) gethostname();

        return in_array(strtolower($name), ['', 'localhost', 'localhost.localdomain'], true) ? '' : $name;
    }

    /**
     * The groups (V2) the simulators use, kept by Robust: the connector of the hypergrid when Robust serves the groups of the
     * hypergrid, else the one of a grid alone.
     *
     * @return list<string>
     */
    private static function groupsLayer(SimulatorPlan|GridInfo $from): array
    {
        $hypergrid = in_array('HGGroupsServiceConnector', $from->connectors, true);

        return [
            ';; The groups are kept by Robust',
            '[Groups]',
            'Enabled = true',
            'Module = "Groups Module V2"',
            'ServicesConnectorModule = "' . ($hypergrid ? 'Groups HG Service Connector' : 'Groups Remote Service Connector') . '"',
            ...$hypergrid ? ['LocalService = remote'] : [],
            'GroupsServerURI = "${Const|PrivURL}:${Const|PrivatePort}"',
            'MessagingEnabled = true',
            'MessagingModule = "Groups Messaging Module V2"',
            'NoticesEnabled = true',
            '',
        ];
    }

    /**
     * The name of the data service of the grid in [DataSnapshot], DATA_SRV_<name>: the nick of the grid, else its name,
     * in PascalCase (vonda: Vonda, my-grid: MyGrid). Any name does, as long as it is the only one of its kind: a
     * simulator can register to several search services (its grid, 2do...).
     */
    public static function dataServiceName(SimulatorPlan $plan): string
    {
        return self::dataServiceNameOf($plan->gridNick, $plan->gridName);
    }

    /** The same, from the nick and the name of a grid. */
    public static function dataServiceNameOf(string $nick, string $name): string
    {
        $text = $nick !== '' ? $nick : $name;
        $words = preg_split('/[^A-Za-z0-9]+/', Slug::ascii($text), -1, PREG_SPLIT_NO_EMPTY);
        $name = implode('', array_map('ucfirst', $words ?: []));

        return $name !== '' ? $name : 'ThisGrid';
    }

    /** The name a simulator was given, from the first line of its config, null when it has none. */
    public static function readName(string $path): ?string
    {
        $head = is_file($path) ? substr(GridFileService::read($path), 0, 512) : '';

        return preg_match('/^;; Generated by opensim setup: simulator (.+) of the grid /m', $head, $m)
            ? trim($m[1])
            : null;
    }

    /** Write the config of the simulator, what it was before kept beside it. */
    public function write(SimulatorPlan $plan): string
    {
        $path = $plan->iniPath();
        is_dir(dirname($path)) || mkdir(dirname($path), 0o755, true);
        $text = $this->render($plan);
        if (is_file($path)) {
            @copy($path, "$path~");
            // What the operator set stays (their other settings, their sections), what the setup manages is what it was asked
            $ini = new IniEditor($text);
            $ini->overlay(TextFileService::read($path));
            $ini->overlay($text);
            $text = $ini->toString();
        }
        file_put_contents($path, $text);

        return $path;
    }

    /** The description of the first region of the simulator. */
    public function renderRegion(SimulatorPlan $plan): string
    {
        return implode("\n", [
            ';; Generated by opensim setup',
            "[{$plan->regionName}]",
            "RegionUUID = {$plan->regionUuid}",
            "Location = {$plan->regionLocation}",
            "SizeX = {$plan->regionSize}",
            "SizeY = {$plan->regionSize}",
            "SizeZ = {$plan->regionSize}",
            'InternalAddress = 0.0.0.0',
            "InternalPort = {$plan->regionPort}",
            'ResolveAddress = False',
            "ExternalHostName = {$plan->externalHost}",
            'MaptileStaticUUID = 00000000-0000-0000-0000-000000000000',
            '',
        ]);
    }

    /** Write the region, unless a file of that name is there already (and it is not a region being changed). */
    public function writeRegion(SimulatorPlan $plan): ?string
    {
        $path = $plan->regionIni();
        if (is_file($path) && !$plan->overwriteRegion) {
            return null;
        }
        @mkdir(dirname($path), 0o755, true);
        file_put_contents($path, $this->renderRegion($plan));

        return $path;
    }
}
